/* Offline-Cache. Bei jeder Änderung an den Dateien VERSION erhöhen, damit Handys die neue Fassung laden. */
const VERSION = "trainingshalle-1.4.0";
const FILES = ["./", "./index.html", "./app.js", "./uebungen.js", "./taktik.js", "./manifest.webmanifest", "./icon.svg", "./icon-192.png", "./icon-512.png"];
self.addEventListener("install", e => { e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES))); self.skipWaiting(); });
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k)))));
  self.clients.claim();
});
// Netzwerk zuerst (damit Updates ankommen), sonst Cache – so funktioniert die App auch ohne Netz in der Halle.
self.addEventListener("fetch", e => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    fetch(e.request).then(r => { const copy = r.clone(); caches.open(VERSION).then(c => c.put(e.request, copy)); return r; })
      .catch(() => caches.match(e.request, { ignoreSearch: true }).then(r => r || caches.match("./index.html")))
  );
});
